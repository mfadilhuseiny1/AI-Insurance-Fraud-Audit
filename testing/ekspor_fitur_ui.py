"""The 124 claim features of a /testing model, with Model 1's gain share of each, for ML Studio's v3 flow drawer (the user,
2026-11-12: "bisa ga ada tombol buat view 124 fitur itu apa aja namanya, soalnya kan banyak fitur tambahan diluar kolom
raw klaim"). Writes web/src/components/aip/fiturV3.ts. Gain = Model 1's booster gain of the feature's own column plus its
four neighbour-mean columns, as a share of all gain. Re-run after a model swap, then build-web.ps1.

Usage: .venv/Scripts/python.exe testing/ekspor_fitur_ui.py [model folder, default model_v3]"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

import joblib
import numpy as np

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "web" / "src" / "components" / "aip" / "fiturV3.ts"


def main(folder: str = "model_v3") -> None:
    b = joblib.load(HERE / folder / "model.joblib")
    sn = list(b["sys_names"])
    n = len(sn)
    g = b["komponen"]["model1"]["model"].booster_.feature_importance("gain").astype(float)
    g = g / g.sum()
    per = [float(sum(g[k * n + i] for k in range(5))) for i in range(n)]
    rows = [{"nama": nm, "gain": round(v, 6)} for nm, v in zip(sn, per)]
    head = (f"// Generated by testing/ekspor_fitur_ui.py from testing/{folder} on {time.strftime('%Y-%m-%d %H:%M')}: the {n} claim features in model\n"
            "// order, each with Model 1's gain share (own column + four neighbour means). Do not edit by hand.\n")
    OUT.write_text(head + f"export const FITUR_MODEL = {json.dumps(folder)};\n"
                   f"export const FITUR_V3: {{ nama: string; gain: number }}[] = {json.dumps(rows, ensure_ascii=False)};\n", "utf-8")
    print("written", OUT, n, "features;", sum(1 for r in rows if r["gain"] == 0), "with zero gain")


if __name__ == "__main__":
    main(*(sys.argv[1:2] or []))
