/** Who calls, and whether they administer (the API's own session check, /api/auth/status; no sign-in configured = local operator). */
async function penelepon(request: Request): Promise<{ nama: string; admin: boolean } | null> {
  try {
    const headers: Record<string, string> = {};
    for (const h of ["cookie", "authorization"]) { const v = request.headers.get(h); if (v) headers[h] = v; }
    const res = await fetch(`${authBase(request)}/api/auth/status`, { headers, cache: "no-store", signal: AbortSignal.timeout(5000) });
    const s = (await res.json()) as { enabled?: boolean; user?: { display_name?: string; name?: string; username?: string; role?: string; emulation?: unknown } | string | null };
    if (s.enabled === false) return { nama: "lokal", admin: true };
    if (!s.user) return null;
    if (typeof s.user === "string") return { nama: s.user, admin: false };
    return { nama: s.user.display_name || s.user.name || s.user.username || "pengguna", admin: s.user.role === "admin" && !s.user.emulation };
  } catch {
    return null;
  }
}

/** Plain one-line text: control characters out, spaces collapsed, cut to a length. */
function teks(v: unknown, maks: number): string {
  return [...String(v ?? "")].filter((c) => { const n = c.charCodeAt(0); return n >= 32 && n !== 127; }).join("").replace(/\s+/g, " ").trim().slice(0, maks);
}

/** A runs.json time ("2026-11-13 15:40", the machine's clock, WIB) as ISO with its offset, so the page shows it as written. */
function iso(s?: string | null): string | null {
  if (!s) return null;
  return /^\d{4}-\d\d-\d\d \d\d:\d\d$/.test(s) ? `${s.replace(" ", "T")}:00+07:00` : s;
}

/** A stored time for sorting (ISO with an offset, or Z). */
const waktu = (s?: string | null) => Date.parse(s ?? "") || 0;

async function ada(f: string): Promise<boolean> {
  try { await stat(f); return true; } catch { return false; }
}

async function tulisJson(f: string, isi: unknown): Promise<void> {
  await mkdir(path.dirname(f), { recursive: true });
  const tmp = `${f}.${process.pid}.${randomBytes(3).toString("hex")}.tmp`;
  await writeFile(tmp, JSON.stringify(isi, null, 1), "utf-8");
  await rename(tmp, f);
}

/** The real path of an allowed IoT root (null when it does not exist). */
async function akarNyata(a: string): Promise<string | null> {
  try { return await realpath(a); } catch { return null; }
}

/** How a folder under an allowed root is shown ("Data Sintetis/x/iot", "data/iot/x"). */
function tampilIot(nyata: string, akar: string, i: number): string {
  const rel = path.relative(akar, nyata).split(path.sep).join("/");
  return `${i === 0 ? "Data Sintetis" : "data/iot"}${rel ? `/${rel}` : ""}`;
}

/** An IoT input folder typed by a person: plain text only, resolved (relative = against the project root, then each allowed root),
 *  symlinks followed, and it must be an existing folder inside "Data Sintetis/" or data/iot. Never reaches a shell (argv only). */
async function periksaFolderIot(v: unknown): Promise<{ folder: string; tampil: string }> {
  const t = String(v ?? "").trim();
  if (!t) throw new Tolak(400, "Isi folder data IoT, atau pilih \"tidak ada\" / \"sintetis\".");
  if (t.length > 400 || [...t].some((c) => { const n = c.charCodeAt(0); return n < 32 || n === 127; })) throw new Tolak(400, "Folder data IoT tidak sah.");
  const akar = await Promise.all(IOT_AKAR.map(akarNyata));
  const calon = path.isAbsolute(t) ? [t] : [path.resolve(PROYEK_ROOT, t), ...IOT_AKAR.map((a) => path.resolve(a, t))];
  for (const c of calon) {
    let nyata: string;
    try { nyata = await realpath(c); } catch { continue; }
    const i = akar.findIndex((a) => a !== null && (nyata === a || nyata.startsWith(a + path.sep)));
    if (i < 0) continue;
    try { if (!(await stat(nyata)).isDirectory()) continue; } catch { continue; }
    if (nyata === akar[i]) throw new Tolak(400, "Pilih folder data IoT di dalam \"Data Sintetis/\" atau data/iot, bukan folder akarnya.");
    return { folder: nyata, tampil: tampilIot(nyata, akar[i] as string, i) };
  }
  throw new Tolak(400, "Folder data IoT tidak ditemukan di dalam \"Data Sintetis/\" atau data/iot.");
}

/** IoT input folders to pick from: data/iot/<x>, and "Data Sintetis/<dataset>/iot*" (folders only; their files are checked by the runner). */
async function daftarIot(): Promise<{ folder: string; tampil: string }[]> {
  const out: { folder: string; tampil: string }[] = [];
  const isi = async (d: string) => { try { return (await readdir(d, { withFileTypes: true })).filter((x) => x.isDirectory()).map((x) => x.name); } catch { return []; } };
  const iotRoot = path.join(DATA, "iot");
  for (const n of (await isi(iotRoot)).sort()) out.push({ folder: path.join(iotRoot, n), tampil: `data/iot/${n}` });
  for (const ds of (await isi(SINTETIS)).filter((n) => DATASET.test(n)).sort()) {
    for (const n of (await isi(path.join(SINTETIS, ds))).filter((x) => /^iot/i.test(x)).sort()) out.push({ folder: path.join(SINTETIS, ds, n), tampil: `Data Sintetis/${ds}/${n}` });
  }
  return out.slice(0, 200);
}

