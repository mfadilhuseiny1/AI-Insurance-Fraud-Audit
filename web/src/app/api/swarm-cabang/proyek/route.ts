/** The project with tema_fokus set and placed after its dataset (the file stays easy to read); every other field kept as it is. */
function denganFokus(p: Proyek, fokus: string[] | null): Proyek {
  const out: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(p)) {
    if (k === "tema_fokus") continue;
    out[k] = v;
    if (k === "dataset") out.tema_fokus = fokus;
  }
  if (!("tema_fokus" in out)) out.tema_fokus = fokus;
  return out as Proyek;
}

/** Projects without tema_fokus get it (idempotent: a project that has the field, null included, is left alone). True = changed. */
function migrasiFokus(b: Berkas): boolean {
  let ubah = false;
  b.proyek = b.proyek.map((p) => {
    if (!p || typeof p !== "object" || "tema_fokus" in p) return p;
    ubah = true;
    const awal = FOKUS_AWAL[p.id];
    return denganFokus(p, awal && awal.dataset === p.dataset ? [...awal.tema] : null);
  });
  return ubah;
}

/** proyek.json, or its seed when it does not exist yet (call inside eksklusif). A file that cannot be read is an error, never
 *  overwritten. Projects from before the theme focus get theirs here, written back once (atomically, every other field kept). */
async function bacaAtauBenih(): Promise<Berkas> {
  let b: Berkas | null = null;
  try {
    b = JSON.parse(await readFile(BERKAS, "utf-8")) as Berkas;
    if (!b || !Array.isArray(b.proyek)) throw new Tolak(500, "proyek.json tidak terbaca (bentuknya salah).");
  } catch (e) {
    if ((e as NodeJS.ErrnoException).code !== "ENOENT") throw e instanceof Tolak ? e : new Tolak(500, `proyek.json tidak terbaca: ${(e as Error).message}`);
    b = null;
  }
  if (b) {
    if (migrasiFokus(b)) await tulisJson(BERKAS, b);
    return b;
  }
  const baru = benih(await bacaRuns());
  await tulisJson(BERKAS, baru);
  return baru;
}

