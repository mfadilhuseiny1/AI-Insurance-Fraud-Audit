/** The branches the reports know (their index.json), for the project form. */
async function daftarKc(runs: RunMeta[], dataset: Dataset[]): Promise<KcInfo[]> {
  const m = new Map<string, KcInfo>();
  const urut = [...runs].sort((a, b) => b.kc - a.kc).slice(0, 8);  // the widest runs first; one 45-branch run names them all
  for (const r of urut) {
    try {
      const idx = JSON.parse(await readFile(path.join(DIR, r.id, "index.json"), "utf-8")) as { kc?: KcInfo[] };
      for (const k of idx.kc ?? []) if (KC.test(k.id) && !m.has(k.id)) m.set(k.id, { id: k.id, nama: k.nama, provinsi: k.provinsi });
    } catch { /* a run without an index */ }
    if (m.size >= 45) break;
  }
  for (const d of dataset) if (d.kc && !m.has(d.kc)) m.set(d.kc, { id: d.kc, nama: d.kc_nama ?? d.kc, provinsi: "" });
  return [...m.values()].sort((a, b) => a.provinsi.localeCompare(b.provinsi) || a.nama.localeCompare(b.nama));
}

// a run's theme counts, per run and branch ("*" = every branch), kept while its index.json is unchanged
const cacheTema = new Map<string, { mtime: number; tema: TemaItem[]; klaim: number }>();

async function temaDariRun(run: string, kc: string | null): Promise<{ tema: TemaItem[]; klaim: number } | null> {
  let mtime = 0;
  try { mtime = (await stat(path.join(DIR, run, "index.json"))).mtimeMs; } catch { return null; }
  const kunci = `${run}|${kc ?? "*"}`;
  const c = cacheTema.get(kunci);
  if (c && c.mtime === mtime) return c;
  let kcs: string[] = [];
  if (kc) kcs = [kc];
  else {
    try { kcs = ((JSON.parse(await readFile(path.join(DIR, run, "index.json"), "utf-8")) as { kc?: { id: string }[] }).kc ?? []).map((k) => k.id).filter((k) => KC.test(k)); } catch { return null; }
  }
  const m = new Map<string, TemaItem>();
  let dibaca = 0;
  for (const k of kcs) {
    try {
      const L = JSON.parse(await readFile(path.join(DIR, run, `kc_${k}.json`), "utf-8")) as { tema?: { kode: string; nama: string; klaim: number; tagihan_rp?: number }[] };
      for (const t of L.tema ?? []) {
        const x = m.get(t.kode) ?? { kode: t.kode, nama: t.nama, klaim: 0, tagihan_rp: 0 };
        x.klaim += t.klaim || 0;
        x.tagihan_rp = (x.tagihan_rp ?? 0) + (t.tagihan_rp || 0);
        m.set(t.kode, x);
      }
      dibaca++;
    } catch { /* this branch is not in the run */ }
  }
  if (!dibaca) return null;
  const tema = [...m.values()].sort((a, b) => b.klaim - a.klaim);
  const hasil = { mtime, tema, klaim: tema.reduce((s, t) => s + t.klaim, 0) };
  cacheTema.set(kunci, hasil);
  return hasil;
}

/** The clinical themes of a dataset and branch, with claim counts: a synthetic dataset's precomputed list
 *  (testing/tema_dataset.py), or, for the generator 3 batch, the newest full report of the branch (a project's own runs first,
 *  `milik`; none before the project exists). */
async function temaData(x: { proyek: string | null; dataset: string; kc: string | null; milik: Set<string> }, runs: RunMeta[], semua: Proyek[]): Promise<DaftarTema> {
  if (x.dataset !== "gen3") {
    let d: { kc?: string | null; klaim?: number; catatan?: string | null; sumber?: string; tema_utama?: string | null; replika?: number; replika_ids?: number[]; tema?: TemaItem[] };
    try { d = JSON.parse(await readFile(path.join(DIR, `tema_${x.dataset}.json`), "utf-8")); } catch {
      throw new Tolak(404, `Jumlah klaim per tema untuk data ini belum dihitung. Jalankan testing/tema_dataset.py --dataset ${x.dataset}.`);
    }
    const tema = (d.tema ?? []).filter((t) => t && typeof t.kode === "string").sort((a, b) => b.klaim - a.klaim);
    return { proyek: x.proyek, dataset: x.dataset, kc: d.kc ?? x.kc, catatan: d.catatan ?? null, klaim: d.klaim ?? tema.reduce((s, t) => s + t.klaim, 0),
      tema_utama: d.tema_utama ?? null, tema, sumber: `Jumlah klaim dihitung dari data ${x.dataset}${d.replika ? ` (gabungan ${d.replika} ulangan setahun)` : ""}.`,
      ...(d.replika ? { replika: d.replika } : {}), ...(Array.isArray(d.replika_ids) ? { replika_ids: d.replika_ids } : {}) };
  }
  const lain = new Set(semua.filter((q) => q.dataset !== "gen3").flatMap((q) => q.audit.map((a) => a.run ?? a.id)));
  const cocok = (r: RunMeta) => !r.tema_pilih?.length && !lain.has(r.id) && (x.kc ? !r.kc_pilih || r.kc_pilih === x.kc : !r.kc_pilih);
  const urut = [...runs].sort((a, b) => waktuRun(b).localeCompare(waktuRun(a))).filter(cocok);
  for (const r of [...urut.filter((y) => x.milik.has(y.id)), ...urut.filter((y) => !x.milik.has(y.id))]) {
    const t = await temaDariRun(r.id, x.kc);
    if (t) return { proyek: x.proyek, dataset: x.dataset, kc: x.kc, catatan: null, klaim: t.klaim, tema_utama: null, tema: t.tema,
      sumber: `Jumlah klaim dari laporan "${r.label}"${x.kc ? "" : ` (${r.kc} kantor cabang)`}.` };
  }
  throw new Tolak(404, "Belum ada laporan untuk menghitung jumlah klaim per tema di kantor cabang ini.");
}

/** The clinical themes a project's audit can pick, with claim counts (its dataset and branch). */
const temaProyek = (p: Proyek, runs: RunMeta[], semua: Proyek[]) =>
  temaData({ proyek: p.id, dataset: p.dataset, kc: p.kc, milik: new Set(p.audit.map((a) => a.run ?? a.id)) }, runs, semua);

/** The themes of a dataset/branch for a new project's focus; when the counts are not there yet, the fixed list without counts
 *  (the same fallback the audit form's check uses). */
async function temaUntukProyekBaru(ds: Dataset, kc: string | null, runs: RunMeta[], semua: Proyek[]): Promise<DaftarTema> {
  try {
    return await temaData({ proyek: null, dataset: ds.id, kc, milik: new Set() }, runs, semua);
  } catch (e) {
    if (!(e instanceof Tolak) || e.kode !== 404) throw e;
    return { proyek: null, dataset: ds.id, kc, klaim: 0, tema_utama: ds.tema_utama, tanpa_jumlah: true, catatan: e.message,
      sumber: "Daftar tema baku, tanpa jumlah klaim.",
      tema: Object.entries(TEMA_NAMA).map(([kode, nama]) => ({ kode, nama, klaim: 0 })) };
  }
}

/** A list of themes from a request ("semua" = every theme = null), checked against the codes allowed; every code listed = null. */
function bacaPilihanTema(v: unknown, daftar: string[], kosong: string, salah: string): string[] | null {
  if (v === "semua") return null;
  if (!Array.isArray(v)) throw new Tolak(400, kosong);
  const kode = [...new Set(v.map((t) => String(t).trim().toUpperCase()))];
  if (!kode.length) throw new Tolak(400, kosong);
  if (kode.length > 40 || kode.some((k) => !daftar.includes(k))) throw new Tolak(400, salah);
  return daftar.length && daftar.every((k) => kode.includes(k)) ? null : kode.sort();
}

type AuditTampil = Omit<Audit, "pid" | "iot"> & { tema_nama: string[]; perintah?: string; iot: { sumber: "sintetis" | "folder"; tampil: string } | null; iot_tampil: string;
  run_info: { id: string; label: string; dijalankan: string | null; model?: string; kc: number; kc_pilih?: string | null; biaya_usd?: number; operasional?: RunMeta["operasional"] } | null;
  progres: { tahap?: string; persen?: number; pesan?: string } | null };

type ProyekTampil = Omit<Proyek, "audit" | "tema_fokus"> & { kc_nama: string | null; dataset_nama: string; virtual?: boolean; audit: AuditTampil[];
  tema_fokus: string[] | null; tema_fokus_nama: string[] };

const PETA_STATUS: Record<string, Status> = { berjalan: "berjalan", running: "berjalan", selesai: "selesai", succeeded: "selesai", gagal: "gagal", failed: "gagal",
  error: "gagal", dibatalkan: "dibatalkan", cancelled: "dibatalkan" };

/** An audit as listed: its status follows runs.json (a run there = finished) and, while it runs, the runner's status file. */
async function tampilAudit(a: Audit, p: Proyek, byId: Map<string, RunMeta>): Promise<AuditTampil> {
  let status = a.status, progres: AuditTampil["progres"] = null, runId = a.run, pesanMati: string | undefined;
  if (status === "berjalan") {
    const s = await bacaStatusAudit(DIR, a.id);
    if (s) {
      progres = { tahap: s.tahap, persen: s.persen, pesan: s.pesan };
      if (s.status && PETA_STATUS[s.status]) status = PETA_STATUS[s.status];
      if (s.run && RUN.test(s.run)) runId = s.run;
      // the status says it runs but its process is gone: stopped, and "Jalankan lagi" resumes it (2026-11-16, killed with the UI)
      if (status === "berjalan" && s.hidup === false) {
        const b = s.progres?.batch != null && s.progres.batch_total ? ` (batch ${s.progres.batch}/${s.progres.batch_total})` : "";
        status = "gagal"; progres = null;
        pesanMati = `Proses audit terhenti di tahap ${s.tahap ?? "-"}${b} tanpa selesai: prosesnya tidak ada lagi. Jalankan lagi untuk melanjutkan; `
          + "batch AI Agent Swarm yang sudah dibaca diambil dari cache, tidak dibayar ulang.";
      }
    }
  }
  const r = byId.get(runId ?? "") ?? byId.get(a.id);
  if (r) status = "selesai";  // the run is in runs.json: the report exists
  const rest: Omit<Audit, "pid" | "iot"> & { pid?: number; iot?: IotPilih | null } = { ...a };
  delete rest.pid;
  delete rest.iot;
  const isi = isiPeluncur(a, p);
  return {
    ...rest, ...(pesanMati ? { pesan: pesanMati } : {}), status, run: r?.id ?? null, progres, tema_nama: (a.tema ?? []).map((k) => TEMA_NAMA[k] ?? k),
    iot: a.iot ? { sumber: a.iot.sumber, tampil: a.iot.sumber === "folder" ? a.iot.tampil : "sintetis" } : null, iot_tampil: iotTampil(a.iot),
    perintah: !r && status !== "berjalan" ? tampilPerintah(argvAudit(isi)) : undefined,
    run_info: r ? { id: r.id, label: r.label, dijalankan: iso(waktuRun(r)), model: r.model, kc: r.kc, kc_pilih: r.kc_pilih, biaya_usd: r.biaya_usd, operasional: r.operasional } : null,
  };
}

function cari(b: Berkas, proyek: unknown, audit?: unknown): { p: Proyek; a: Audit | null } {
  const pid = String(proyek ?? "");
  if (!PROYEK.test(pid)) throw new Tolak(400, "Proyek tidak dikenal.");
  const p = b.proyek.find((x) => x.id === pid);
  if (!p) throw new Tolak(404, "Proyek tidak ditemukan.");
  if (audit === undefined) return { p, a: null };
  const aid = String(audit ?? "");
  if (!RUN.test(aid)) throw new Tolak(400, "Audit tidak dikenal.");
  const a = p.audit.find((x) => x.id === aid);
  if (!a) throw new Tolak(404, "Audit tidak ditemukan di proyek ini.");
  return { p, a };
}

/** An audit's fields from a request (audit_baru, ubah_audit): its name, themes, cost cap and IoT data, checked. */
async function isianAudit(body: Record<string, unknown>, p: Proyek, runs: RunMeta[], semua: Proyek[], admin: boolean):
  Promise<{ label: string; tema: string[] | null; batas_usd: number; iot: IotPilih | null; replika: number | null }> {
  const label = teks(body.label, 120);
  if (label.length < 3) throw new Tolak(400, "Beri nama audit (paling sedikit 3 huruf).");
  // the themes: "semua", or codes of this project's theme list (the static list when the counts are not there)
  let daftar: string[] = Object.keys(TEMA_NAMA);
  let nReplika = 0;
  try { const dt = await temaProyek(p, runs, semua); daftar = dt.tema.map((t) => t.kode); nReplika = dt.replika ?? 0; } catch { /* counts not computed yet */ }
  if (body.tema !== "semua" && !Array.isArray(body.tema)) throw new Tolak(400, "Pilih tema audit.");
  const tema = bacaPilihanTema(body.tema, daftar, "Pilih paling sedikit satu tema, atau semua tema.", "Ada tema yang tidak dikenal untuk data proyek ini.");
  const maks = admin ? BATAS_MAKS_ADMIN : BATAS_MAKS;
  const batas = body.batas_usd == null || body.batas_usd === "" ? BATAS_BAWAAN : Number(body.batas_usd);
  if (!Number.isFinite(batas) || batas <= 0) throw new Tolak(400, "Batas biaya harus lebih dari $0.");
  if (batas > maks) throw new Tolak(400, admin ? `Batas biaya paling tinggi $${maks}.` : `Batas biaya paling tinggi $${maks}; minta admin untuk batas yang lebih tinggi.`);
  // the IoT data: none, synthetic, or a folder under an allowed root (theme datasets only: the runner reads those)
  const mode = body.iot == null || body.iot === "" ? "tidak" : String(body.iot);
  let iot: IotPilih | null = null;
  if (mode === "sintetis") iot = { sumber: "sintetis" };
  else if (mode === "folder") iot = { sumber: "folder", ...(await periksaFolderIot(body.iot_folder)) };
  else if (mode !== "tidak") throw new Tolak(400, "Pilihan data IoT tidak dikenal.");
  if (iot && p.dataset === "gen3") throw new Tolak(400, "Data IoT hanya untuk proyek dengan data tema (folder Data Sintetis).");
  // the data size: every replica, or the last N of a theme dataset (jalan_kc_tema.py --replika-terakhir)
  const ukuran = body.replika == null || body.replika === "" || body.replika === "semua" ? null : Number(body.replika);
  if (ukuran !== null) {
    if (p.dataset === "gen3") throw new Tolak(400, "Ukuran data hanya untuk proyek dengan data tema (folder Data Sintetis).");
    if (!Number.isInteger(ukuran) || ukuran < 1 || (nReplika && ukuran > nReplika)) throw new Tolak(400, `Ukuran data: 1 sampai ${nReplika || "?"} ulangan, atau semua.`);
  }
  return { label, tema, batas_usd: Math.round(batas * 100) / 100, iot, replika: ukuran && nReplika && ukuran >= nReplika ? null : ukuran };
}

function gagal(e: unknown): Response {
  if (e instanceof Tolak) return Response.json({ error: e.message }, { status: e.kode });
  return Response.json({ error: `Gagal: ${String((e as Error)?.message ?? e)}` }, { status: 500 });
}

